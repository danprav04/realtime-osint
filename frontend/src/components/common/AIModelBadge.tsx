'use client';

import React from 'react';
import Link from 'next/link';
import { Sparkles, Zap, Layers, Cpu, Server, Bot } from 'lucide-react';
import { AIModelInfo } from '@/lib/types';
import { getProviderBadgeStyles, formatProviderName, parseModelProvider, cn } from '@/lib/utils';

export interface AIModelBadgeProps {
  provider?: string;
  model?: string;
  provenance?: AIModelInfo;
  size?: 'xs' | 'sm';
  labelPrefix?: string;
  showIcon?: boolean;
  linkToSettings?: boolean;
  className?: string;
}

export function AIModelBadge({
  provider: propProvider,
  model: propModel,
  provenance,
  size = 'xs',
  labelPrefix,
  showIcon = true,
  linkToSettings = false,
  className,
}: AIModelBadgeProps) {
  // Resolve model and provider
  let finalProvider = propProvider;
  let finalModel = propModel;

  if (provenance) {
    finalProvider = provenance.provider;
    finalModel = provenance.model;
  } else if (propModel && !propProvider) {
    const parsed = parseModelProvider(propModel);
    finalProvider = parsed.provider;
    finalModel = parsed.model;
  }

  const cleanProvider = formatProviderName(finalProvider || 'AI');
  const cleanModel = finalModel || 'pipeline-model';
  const styles = getProviderBadgeStyles(cleanProvider);

  // Select appropriate brand icon
  const pLower = cleanProvider.toLowerCase();
  const IconComponent = (() => {
    if (pLower.includes('gemini') || pLower.includes('google')) return Sparkles;
    if (pLower.includes('groq')) return Zap;
    if (pLower.includes('aihubmix') || pLower.includes('aihub')) return Layers;
    if (pLower.includes('hugging') || pLower.includes('hf')) return Server;
    if (pLower.includes('rule') || pLower.includes('heuristic') || pLower.includes('system')) return Cpu;
    return Bot;
  })();

  const tooltipText = `AI Output generated by ${cleanModel} via ${cleanProvider} provider`;

  const content = (
    <span
      className={cn(
        'inline-flex items-center rounded border font-mono transition-colors tracking-tight select-none',
        styles.badge,
        size === 'xs' ? 'text-[9.5px] px-1.5 py-0.5 gap-1' : 'text-[11px] px-2 py-0.5 gap-1.5',
        linkToSettings && 'cursor-pointer hover:opacity-90',
        className
      )}
      title={tooltipText}
    >
      {showIcon && (
        <IconComponent
          className={cn(
            'shrink-0',
            size === 'xs' ? 'w-2.5 h-2.5' : 'w-3 h-3'
          )}
        />
      )}
      {labelPrefix && <span className="opacity-70 font-normal">{labelPrefix}</span>}
      <span className="font-semibold">{cleanProvider}</span>
      <span className="opacity-40">·</span>
      <span className="truncate max-w-[150px] sm:max-w-[220px]" title={cleanModel}>
        {cleanModel}
      </span>
    </span>
  );

  if (linkToSettings) {
    return (
      <Link href="/settings" title={`${tooltipText} (Click to configure in Settings)`}>
        {content}
      </Link>
    );
  }

  return content;
}
